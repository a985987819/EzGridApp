import { useState } from 'react'
import { Button, Card, Input, Modal, notificationOpen } from 'animal-island-ui'
import { useApp } from '../store/useApp'
import { buildLadder, gridStatuses, type GridMode, type LadderInput } from '../domain/gridStrategy'
import { toCents } from '../domain/money'
import { price, qty, signedMoney } from '../ui/format'
import { useScrollHold } from '../ui/scrollHold'
import type { ExtraTarget } from '../domain/types'

export function GridPlanner({ stockName }: { stockName: string }) {
  const { ledger, records, executions, extraTargets, recordNo, saveGridLadder, removeExtraTarget, setSellGridMode } = useApp()
  const [open, setOpen] = useState(false)
  const [selected, setSelected] = useState<string[]>([])
  const [sourceTarget, setSourceTarget] = useState<string | null>(null)
  const [mode, setMode] = useState<GridMode>('repair')
  const [start, setStart] = useState('')
  const [step, setStep] = useState('0.30')
  const [gap, setGap] = useState('0.30')
  const [per, setPer] = useState('500')
  const [direction, setDirection] = useState<1 | -1>(1)
  const [commandId, setCommandId] = useState('')
  const [busy, setBusy] = useState(false)
  useScrollHold(open)
  const label = (lotId: string) => {
    const lot = ledger.lots.find(l => l.id === lotId)
    return lot?.strategyOrigin?.mode === 'baseT' ? `恢复底仓（${lot.strategyOrigin.sourceLotId.startsWith('lot:exec:') ? '回补批次' : `第 ${recordNo.of(Number(lot.strategyOrigin.sourceLotId.slice(4)))} 笔`}）`
      : lotId.startsWith('lot:exec:') ? '回补批次' : `第 ${recordNo.of(Number(lotId.slice(4)))} 笔`
  }
  const free = ledger.lots.filter(l => l.stockName === stockName && ledger.targets.some(t => t.lotId === l.id && t.autoGenerated && t.qty > 0))
  const statuses = gridStatuses(extraTargets, records, executions, ledger.lots).filter(s => s.stockName === stockName && s.qty > 0)
  const existing = ledger.orders.filter(o=>o.stockName===stockName&&o.sellFirst&&o.execQty===0&&records.some(r=>r.sourceRow===o.sourceRow&&!r.soldLotId&&r.buyPriceCents===null))
  const startPlan = (target?: ExtraTarget) => {
    setSelected(target ? [target.lotId] : [])
    setSourceTarget(target ? `target:${target.id}` : null)
    setStart(target ? price(target.priceCents) : free[0]?.targetPriceCents ? price(free[0].targetPriceCents) : '')
    setMode(target?.strategy?.mode ?? 'repair')
    setCommandId(crypto.randomUUID());setOpen(true)
  }
  const input: LadderInput = { lotIds: selected, startCents: toCents(start) ?? 0, stepCents: toCents(step) ?? 0,
    rebuyGapCents: toCents(gap) ?? 0, perQty: Number(per), direction, mode,
    ...(sourceTarget ? {targetIds:[sourceTarget]} : {}) }
  let preview: ExtraTarget[] = [], problem = ''
  if (open) try { preview = buildLadder(ledger, input, commandId, 0) } catch (e) { problem = e instanceof Error ? e.message : String(e) }
  async function save() {
    if (busy || problem) return
    setBusy(true)
    try { await saveGridLadder(input, commandId);setOpen(false);notificationOpen({message:'拆档计划已保存',description:'原始买入记录未改变，成交后按来源扣份额',type:'success'}) }
    catch (e) { notificationOpen({message:'拆档未保存',description:e instanceof Error?e.message:String(e),type:'error'}) }
    finally {setBusy(false)}
  }
  return <>
    <Card data-testid="grid-strategies">
      <div className="sec-head"><strong>连续拆档与策略</strong><div className="spacer"/><Button data-action="grid-open" onClick={()=>startPlan()}>批量拆档</Button></div>
      <p className="tiny muted">原单保留，按剩余份额连续排档；先卖后买可选择亏损回本或底仓做T。</p>
      {existing.length>0 && <details data-testid="grid-existing"><summary className="tiny">未回补先卖单 · 选择模式</summary>
        <p className="tiny muted">做T需先完整关联到一个高位批次；已有回补的历史不自动迁移。</p>
        {existing.map(o=><div key={o.id} className="line wrap-row"><span>第 {recordNo.of(o.sourceRow)} 笔 · 当前{o.strategyMode==='baseT'?'底仓做T':'亏损回本'}</span>
          <select aria-label={`第${recordNo.of(o.sourceRow)}笔模式`} data-grid-existing={o.sourceRow} value={o.strategyMode??'repair'} disabled={busy} onChange={e=>{
            setBusy(true);void setSellGridMode(o.sourceRow,e.target.value as GridMode).catch(err=>notificationOpen({message:'模式未保存',description:String(err),type:'error'})).finally(()=>setBusy(false))
          }}><option value="repair">亏损回本</option><option value="baseT">底仓做T</option></select></div>)}
      </details>}
      {statuses.length > 0 && <details data-testid="grid-status"><summary className="tiny">策略台账 · {statuses.length} 档</summary>
        {statuses.map(s => <div key={s.id} className="line wrap-row" data-grid-id={s.id} data-grid-mode={s.mode}>
          <div className="left"><div className="t1">{s.mode==='baseT'?'底仓做T':'亏损回本'} · {label(s.lotId)}</div>
            <div className="t2 num">卖 {price(s.sellPriceCents)} → 买回 {price(s.rebuyPriceCents)} · {qty(s.qty)} 股</div>
            <div className="tiny">未卖 {qty(s.unfilledQty)} · 待买回 {qty(s.pendingQty)} · 已买回 {qty(s.repaidQty)} · 当前持有 {qty(s.holdingQty)}</div>
            <div className="tiny">回补后{s.mode==='baseT'?'恢复底仓目标':'计划再卖'} {price(s.nextSellPriceCents)}
              {s.mode==='baseT' && <> · 已完成做T价差 {signedMoney(s.spreadCents)}（单列，不重复加总）</>}</div>
          </div>
          {s.unfilledQty > 0 && <Button size="small" data-action="grid-resplit" onClick={()=>startPlan(extraTargets.find(t=>t.id===s.id))}>再拆剩余</Button>}
          {s.soldQty===0 && <Button size="small" type="text" onClick={()=>void removeExtraTarget(s.id).catch(e=>notificationOpen({message:'删除未完成',description:String(e),type:'error'}))}>撤掉此档</Button>}
        </div>)}
      </details>}
    </Card>
    <Modal variant="default" className="booking-modal grid-planner-modal" open={open} title={sourceTarget?'再次拆分剩余份额':'批量连续拆档'} typewriter={false} onClose={()=>!busy&&setOpen(false)} footer={<div className="row">
      <Button type="primary" data-emphasis="true" data-action="grid-save" disabled={busy||!!problem||!preview.length} onClick={()=>void save()}>保存拆档计划</Button>
      <Button disabled={busy} onClick={()=>setOpen(false)}>取消</Button></div>}>
      <div className="stack grid-planner-body">
      <p className="hint-block">{stockName} · 只改变未来计划，保留真实买入成本。相邻档距与每轮回补价差分别设置。</p>
      {!sourceTarget && <div role="group" aria-label="选择拆档来源" className="grid-source-list"><p className="tiny muted">选择来源（按勾选顺序连续排档）</p>
        {free.map(l=><label key={l.id}><input type="checkbox" data-grid-lot={l.id} checked={selected.includes(l.id)} onChange={e=>setSelected(prev=>e.target.checked?[...prev,l.id]:prev.filter(id=>id!==l.id))}/>
          {label(l.id)} · 成本{price(l.buyPriceCents)} · 可拆{qty(ledger.targets.filter(t=>t.lotId===l.id&&t.autoGenerated).reduce((a,t)=>a+t.qty,0))}股</label>)}
        {!free.length&&<p>没有可用的未占用份额；可在策略台账中选择“再拆剩余”。</p>}
      </div>}
      <div className="type-toggle" style={{marginBlock:10}}><Button data-grid-mode-select="repair" type={mode==='repair'?'primary':'default'} onClick={()=>setMode('repair')}>亏损回本</Button><Button data-grid-mode-select="baseT" type={mode==='baseT'?'primary':'default'} onClick={()=>setMode('baseT')}>底仓做T</Button></div>
      <p className="tiny muted">{mode==='repair'?'高位卖出按成本计亏；回补低位库存计划回到本档卖价，后续实际盈亏归原链。':'卖出后暂停该份高位卖量；买回多少恢复多少原目标，做T价差单列，实际成本与亏损保留。'}</p>
      <div className="form-grid">
        <label><span>起始卖价</span><Input data-grid-field="start" value={start} onChange={e=>setStart(e.target.value)}/></label>
        <label><span>相邻档距（元）</span><Input data-grid-field="step" value={step} onChange={e=>setStep(e.target.value)}/></label>
        <label><span>每档股数</span><Input data-grid-field="qty" value={per} onChange={e=>setPer(e.target.value)}/></label>
        <label><span>卖价减回补买价（元）</span><Input data-grid-field="gap" value={gap} onChange={e=>setGap(e.target.value)}/></label>
        <label><span>排档方向</span><select data-grid-field="direction" value={direction} onChange={e=>setDirection(Number(e.target.value) as 1|-1)}><option value="1">逐档升价</option><option value="-1">逐档降价</option></select></label>
      </div>
      {problem ? <p className="hint-block">{problem}</p> : <div data-testid="grid-preview"><p>预览 {preview.length} 档 · 合计 {qty(preview.reduce((a,t)=>a+t.qty,0))} 股</p>
        {preview.map((t,i)=><div className="tiny grid-preview-row" key={t.id}>{i+1}. {label(t.lotId)} · 卖{price(t.priceCents)}×{qty(t.qty)} → 买回{price(t.strategy!.rebuyPriceCents)} · 后续卖{price(t.strategy!.nextSellPriceCents)}</div>)}
      </div>}
      </div>
    </Modal>
  </>
}
