import { useState } from 'react'
import { Button, Input, Modal, Tag, notificationOpen } from 'animal-island-ui'
import { useApp } from '../store/useApp'
import { centsToYuan, toCents } from '../domain/money'
import { inputOrDefault } from '../domain/formDefaults'
import { enterSubmit } from '../ui/enterSave'
import { money, price, qty } from '../ui/format'
import type { BuySplit, SellTarget } from '../domain/types'

/**
 * V9.66：挂单页行内拆分——不用再跳明细抽屉。
 * - kind='buy'：把一张先卖后买单的回补按价位拆成多档买入（buyTargets，V9.50）。
 * - kind='sell'：把一个批次的待卖按价位拆成多档卖出（extraTargets，V6）。
 * 缺省价与留空默认值同抽屉 V9.62 口径：派生价 > 推导价（间隔），股数默认「还能拆的量」。
 * 传 sellRow（买入拆分）或 lotId（卖出拆分），其余全部自己从账本取。
 */
export function SplitModal(props: { kind: 'buy' | 'sell'; sellRow?: number; lotId?: string; onClose: () => void }) {
  const { kind, sellRow, lotId, onClose } = props
  const { ledger, stocks, extraTargets, buyTargets, addBuyTarget, removeBuyTarget, addExtraTarget, removeExtraTarget } = useApp()
  const [pText, setPText] = useState('')
  const [qText, setQText] = useState('')

  const order = kind === 'buy' ? ledger.orders.find((o) => o.sourceRow === sellRow) : undefined
  const sell = kind === 'buy' ? ledger.sells.find((s) => s.sourceRow === sellRow) : undefined
  const lot = kind === 'sell' ? ledger.lots.find((l) => l.id === lotId) : undefined
  const stockName = order?.stockName ?? lot?.stockName ?? ''
  const interval = stocks.find((s) => s.name === stockName)?.intervalCents ?? 0

  /** 还能拆的量（与抽屉 splitLeftOf / buySplitLeftOf 同口径） */
  const left =
    kind === 'buy' && order
      ? Math.max(0, order.baseQty - buyTargets.filter((t) => t.sellRow === order.sourceRow).reduce((a, t) => a + t.qty, 0))
      : lot
        ? Math.max(0, lot.remainingQty - extraTargets.filter((t) => t.lotId === lot.id).reduce((a, t) => a + t.qty, 0))
        : 0
  /** 缺省价：派生回补价 > 卖价−间隔；E 列目标价 > 买入价+间隔（V9.62 同口径） */
  const fallbackPrice =
    kind === 'buy'
      ? (sell?.rebuyPriceCents ??
        (sell?.priceCents != null && interval > 0 && sell.priceCents - interval > 0 ? sell.priceCents - interval : null))
      : (lot?.targetPriceCents ??
        (lot && lot.buyPriceCents > 0 && interval > 0 ? lot.buyPriceCents + interval : null))

  const buySplits: BuySplit[] = kind === 'buy' ? ledger.buySplits.filter((b) => b.sourceRow === sellRow && b.split) : []
  const sellTargets: SellTarget[] = kind === 'sell' ? ledger.targets.filter((t) => t.lotId === lotId && !t.autoGenerated) : []

  function confirmSplit() {
    const p = toCents(inputOrDefault(pText, fallbackPrice === null ? '' : centsToYuan(fallbackPrice)))
    const raw = Number(inputOrDefault(qText, String(left)))
    if (p === null || p <= 0 || !Number.isInteger(raw) || raw <= 0) {
      notificationOpen({ message: '拆分价和股数都要填', type: 'warning' })
      return
    }
    if (left <= 0) {
      notificationOpen({ message: kind === 'buy' ? '这笔已经没有可拆的回补份额了' : '这批已经没有可拆的份额了', type: 'warning' })
      return
    }
    const q = Math.min(raw, left)
    if (kind === 'buy' && sellRow) {
      void addBuyTarget(sellRow, p, q).then(() => {
        setPText('')
        setQText('')
        notificationOpen({
          message: '已拆分买入',
          description: raw > left ? `超过还能拆的 ${left} 股，已按剩余量拆分` : '挂单页按拆出来的档显示',
          type: 'success',
        })
      })
    } else if (kind === 'sell' && lotId) {
      void addExtraTarget(lotId, p, q).then(() => {
        setPText('')
        setQText('')
        notificationOpen({
          message: '已拆分目标',
          description: raw > left ? `超过还能拆的 ${left} 股，已按剩余量拆分` : '自动目标按剩余量缩减',
          type: 'success',
        })
      })
    }
  }

  return (
    <Modal
      open
      title={kind === 'buy' ? '拆分买入' : '拆分卖出'}
      typewriter={false}
      onClose={onClose}
      footer={
        <div className="row nowrap" style={{ gap: 8 }}>
          <Button type="primary" style={{ flex: 1 }} data-action="split-confirm" onClick={confirmSplit}>拆分</Button>
          <Button onClick={onClose}>取消</Button>
        </div>
      }
    >
      <div className="stack tight" onKeyDown={enterSubmit(confirmSplit)} data-testid="split-modal">
        <p className="hint-block" style={{ margin: 0 }}>
          {kind === 'buy'
            ? `${stockName} · 还没回补 ${qty(left)} 股，拆成多档买入后挂单页按档显示；成交按价格落档。`
            : `${stockName} · 批次剩余 ${qty(left)} 股，拆成多档卖出分批止盈；手动目标先占份额，剩下的仍挂在 E 列价上。`}
        </p>
        {(buySplits.length > 0 || sellTargets.length > 0) && (
          <div className="data-block">
            {buySplits.map((b, i) => (
              <div key={b.key} className="line">
                <div className="left">
                  <div className="t1 num">
                    第 {i + 1}/{buySplits.length} 档 · {price(b.priceCents)} × {qty(b.plannedQty)}
                  </div>
                  <div className="t2">
                    手动拆分
                    {b.executedQty > 0 ? ` · 已回补 ${qty(b.executedQty)} · 还剩 ${qty(b.qty)}` : ''}
                  </div>
                </div>
                {b.targetId && (
                  <Button size="small" danger onClick={() => void removeBuyTarget(b.targetId!)}>
                    删除
                  </Button>
                )}
              </div>
            ))}
            {sellTargets.map((t, i) => (
              <div key={t.id} className="line">
                <div className="left">
                  <div className="t1 num">
                    第 {i + 1}/{sellTargets.length} 档 · {price(t.priceCents)} × {qty(t.qty)}
                  </div>
                  <div className="t2">手动拆分 · 预期 {money(t.expectProfitCents)}</div>
                </div>
                <Button size="small" danger onClick={() => void removeExtraTarget(t.id.replace('target:', ''))}>
                  删除
                </Button>
              </div>
            ))}
          </div>
        )}
        <div className="row nowrap" style={{ gap: 6 }}>
          <Input
            className="grow"
            value={pText}
            onChange={(e) => setPText(e.target.value)}
            placeholder={fallbackPrice === null ? (kind === 'buy' ? '拆分买入价' : '拆分目标价') : centsToYuan(fallbackPrice)}
            aria-label={kind === 'buy' ? '拆分买入价' : '拆分目标价'}
          />
          <Input
            className="grow"
            value={qText}
            onChange={(e) => setQText(e.target.value)}
            placeholder={String(left)}
            aria-label={kind === 'buy' ? '拆分买入股数' : '拆分股数'}
          />
          <Tag size="small" variant="soft" color={left > 0 ? 'app-teal' : 'app-yellow'}>
            可拆 {qty(left)}
          </Tag>
        </div>
        <p className="tiny muted" style={{ margin: 0 }}>
          留空采用框内默认值（价格自动推导、股数 = 还能拆的量）——直接点「拆分」即可；总额度不会超过还能拆的量。
        </p>
      </div>
    </Modal>
  )
}
