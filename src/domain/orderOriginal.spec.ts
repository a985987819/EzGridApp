import { describe, expect, it } from 'vitest'
import { buildLedger } from './ledger'
import { mergeTargetRows } from './merge'
import { buildBuySuggestions } from './suggestions'
import type { NextRoundBuyRow } from './buyBoard'
import type { BuySplit, Lot, RawRecord, RebuyExecution, SellTarget, StockConfig, TradePlan } from './types'

const stock: StockConfig = { id: 'stock:T', name: 'T', intervalCents: 200, priceLimitType: 'main_10' }
const record = (sourceRow: number, fields: Partial<RawRecord> = {}): RawRecord => ({
  sourceRow, stockName: 'T', buyDateSerial: 46000, buyPriceCents: 500, buyQtyRaw: 1000,
  qtyNeedsDerive: false, targetPriceCents: 900, targetNeedsDerive: false, soldQty: 0,
  sellDateSerial: 46010, earlyBuyPriceCents: null, rawProfitCents: null, importKey: `k${sourceRow}`, ...fields,
})
const naked = record(9, { buyDateSerial: null, buyPriceCents: null, buyQtyRaw: null, soldQty: 1000, targetPriceCents: 800, earlyBuyPriceCents: 600 })
const execution = (fields: Partial<RebuyExecution> = {}): RebuyExecution => ({
  id: 'e', orderId: 'rb:sell:9', sellExecId: 'sell:9', stockId: stock.id, stockName: 'T', qty: 200,
  priceCents: 600, rewardQty: 0, groupKeyAtExecution: 'stock:T|600', at: 1793000000000, ...fields,
})
const plan = (kind: TradePlan['kind'], refId: string, priceCents: number, qty: number, at = 1): TradePlan => ({ id: `p:${refId}`, kind, refId, priceCents, qty, at })
const split = (sourceRow: number, priceCents: number, qty: number, fields: Partial<BuySplit> = {}): BuySplit => ({
  key: `rb:sell:${sourceRow}`, orderId: `rb:sell:${sourceRow}`, sellExecId: `sell:${sourceRow}`, sourceRow, stockName: 'T',
  priceCents, qty, baseRemainingQty: qty, plannedQty: qty, executedQty: 0, split: false, targetId: null, sellFirst: true, ...fields,
})
const next = (fields: Partial<NextRoundBuyRow> = {}): NextRoundBuyRow => ({
  key: 'buy:merge:m', stockName: 'T', priceCents: 600, qty: 800, amountCents: 480000,
  rows: [2, 3], sourceQty: { 2: 500, 3: 300 }, merged: true, anchorRow: 2,
  earliestBuyDate: '2025-12-01', lastSoldAt: '2026-01-01', repaid: false, ...fields,
})
const lot = (sourceRow: number, remainingQty = 500): Lot => ({
  id: `lot:${sourceRow}`, sourceRow, stockId: stock.id, stockName: 'T', buyDate: '2025-12-01', buyPriceCents: 500,
  qty: remainingQty, soldQty: 0, remainingQty, targetPriceCents: 700, needsPrice: false, importKey: `k${sourceRow}`,
})
const target = (sourceRow: number, priceCents: number, qty = 500, fields: Partial<SellTarget> = {}): SellTarget => ({
  id: `target:lot:${sourceRow}`, lotId: `lot:${sourceRow}`, stockId: stock.id, stockName: 'T', priceCents, qty,
  autoGenerated: true, amountCents: priceCents * qty, expectProfitCents: (priceCents - 500) * qty, ...fields,
})

describe('改单前的推荐参考只展示当前未完成份额', () => {
  it('买单整单计划与建议计划叠加，仍保留当前800股的原600分推荐；清除后与实际推荐一致', () => {
    const plans = [plan('buy', 'rb:sell:9', 550, 100), plan('buy', 'buy:cover:T:550', 500, 300, 2)]
    const records = [naked], executions = [execution()]
    const before = JSON.stringify({ records, executions, plans })
    const ledger = buildLedger(records, [stock], { executions, plans })
    expect(ledger.buySplits[0]).toMatchObject({ priceCents: 550, originalPriceCents: 600, qty: 800 })
    const splitsBefore = JSON.stringify(ledger.buySplits)
    const [edited] = buildBuySuggestions(ledger.buySplits, [], plans)
    expect(edited).toMatchObject({ key: 'buy:cover:T:550', priceCents: 500, qty: 100, amountCents: 50000, originalQty: 800, originalAmountCents: 480000 })
    expect(edited.sources.map(s => s.qty)).toEqual([100])
    expect(edited.planRefs).toContain('rb:sell:9')
    expect(JSON.stringify(ledger.buySplits)).toBe(splitsBefore)
    expect(JSON.stringify({ records, executions, plans })).toBe(before)
    const clean = buildLedger(records, [stock], { executions })
    const [cleared] = buildBuySuggestions(clean.buySplits, [], [])
    expect(cleared).toMatchObject({ priceCents: 600, qty: 800, amountCents: 480000, originalQty: 800, originalAmountCents: 480000 })
  })

  it('下一轮合并来源只留下第一份成交贡献，原推荐仍包含所有800股和原价', () => {
    const n = next(), plans = [plan('buy', n.key, 550, 200), plan('buy', 'buy:optional:T:550', 500, 100, 2)]
    const before = JSON.stringify({ n, plans })
    const [r] = buildBuySuggestions([], [n], plans)
    expect(r).toMatchObject({ priceCents: 500, qty: 100, amountCents: 50000, originalQty: 800, originalAmountCents: 480000 })
    expect(r.sources).toEqual([{ kind: 'next', id: n.key, row: 2, qty: 100 }])
    expect(JSON.stringify({ n, plans })).toBe(before)
    const [clear] = buildBuySuggestions([], [n], [])
    expect(clear).toMatchObject({ qty: 800, amountCents: 480000, originalQty: 800, originalAmountCents: 480000 })
  })

  it('买单撞价按各自原价累计金额，同时保留现有来源贡献与身份', () => {
    const splits = [split(9, 550, 300, { originalPriceCents: 600 }), split(10, 650, 500)]
    const [r] = buildBuySuggestions(splits, [], [plan('buy', 'buy:cover:T:550', 650, 100)])
    expect(r).toMatchObject({ key: 'buy:cover:T:650', priceCents: 650, qty: 600, amountCents: 390000, originalQty: 800, originalAmountCents: 505000 })
    expect(r.sources.map(s => [s.row, s.qty])).toEqual([[9, 100], [10, 500]])
    expect(r.members).toEqual([{ key: 'buy:cover:T:550', qty: 100 }, { key: 'buy:cover:T:650', qty: 500 }])
  })

  it('买入参考按欠股/可选及显式策略隔离，默认策略保持原推荐身份', () => {
    const splits = [
      split(9, 600, 300, { strategyMode: 'repair', strategyIsDefault: true }),
      split(10, 600, 200, { strategyMode: 'repair', originalPriceCents: 620 }),
      split(11, 600, 100, { strategyMode: 'baseT', originalPriceCents: 640 }),
    ]
    const board = buildBuySuggestions(splits, [next({ key: 'buy:2', qty: 100, rows: [2], sourceQty: { 2: 100 } })], [plan('buy', 'buy:cover:T:600', 580, 100)])
    expect(board).toHaveLength(4)
    expect(board.find(r => r.key === 'buy:cover:T:600')).toMatchObject({ qty: 100, originalQty: 300, originalAmountCents: 180000 })
    expect(board.find(r => r.key === 'buy:cover:T:600:repair')).toMatchObject({ qty: 200, originalQty: 200, originalAmountCents: 124000 })
    expect(board.find(r => r.key === 'buy:cover:T:600:baseT')).toMatchObject({ qty: 100, originalQty: 100, originalAmountCents: 64000 })
    expect(board.find(r => r.key === 'buy:optional:T:600')).toMatchObject({ qty: 100, originalQty: 100, originalAmountCents: 60000 })
  })

  it('同张母单拆成两档后，只累计各档当前剩余及未成交奖励，不重复母单总量', () => {
    const r = record(9, { buyQtyRaw: 500, soldQty: 500, targetPriceCents: 700, earlyBuyPriceCents: 500 })
    const buyTargets = [{ id: 'a', sellRow: 9, priceCents: 450, qty: 300, at: 1 }, { id: 'b', sellRow: 9, priceCents: 500, qty: 200, at: 2 }]
    const initial = buildLedger([r], [stock], { buyTargets })
    const [merged] = buildBuySuggestions(initial.buySplits, [], [plan('buy', 'buy:optional:T:450', 500, 100)])
    expect(merged).toMatchObject({ qty: 500, originalQty: 700, originalAmountCents: 335000 })
    expect(merged.sources.map(s => s.qty)).toEqual([100, 400])
    const after = buildLedger([r], [stock], { buyTargets, executions: [execution({ qty: 400, rewardQty: 200, buyTargetId: 'b', priceCents: 500, groupKeyAtExecution: 'stock:T|500' })] })
    const [pending] = buildBuySuggestions(after.buySplits, [], [])
    expect(pending).toMatchObject({ priceCents: 450, qty: 300, originalQty: 300, originalAmountCents: 135000 })
  })

  it('默认剩余档保留整单计划前价格，手动拆分档各自保留原拆分价格', () => {
    const ledger = buildLedger([naked], [stock], {
      buyTargets: [{ id: 'cheap', sellRow: 9, priceCents: 500, qty: 300, at: 1 }],
      executions: [execution({ qty: 100, priceCents: 500, buyTargetId: 'cheap' })],
      plans: [plan('buy', 'rb:sell:9', 550, 400)],
    })
    expect(ledger.buySplits.map(b => [b.priceCents, b.originalPriceCents, b.qty])).toEqual([[500, 500, 200], [550, 600, 700]])
    const board = buildBuySuggestions(ledger.buySplits, [], [])
    expect(board.map(r => [r.originalQty, r.originalAmountCents])).toEqual([[700, 420000], [200, 100000]])
  })

  it('卖出整组1000股缩到300股，第二个来源归零仍计入原推荐', () => {
    const targets = [target(2, 700), target(3, 700)], lots = [lot(2), lot(3)]
    const plans = [plan('sell', 'sell:T:700', 750, 300)]
    const before = JSON.stringify({ targets, lots, plans })
    const [r] = mergeTargetRows({ targets, lots, merges: [], plans })
    expect(r).toMatchObject({ key: 'target:lot:2', priceCents: 750, qty: 300, amountCents: 225000, originalQty: 1000, originalAmountCents: 700000 })
    expect(r.targets.map(t => [t.id, t.qty])).toEqual([['target:lot:2', 300]])
    expect(JSON.stringify({ targets, lots, plans })).toBe(before)
    const [clear] = mergeTargetRows({ targets, lots, merges: [] })
    expect(clear).toMatchObject({ priceCents: 700, qty: 1000, amountCents: 700000, originalQty: 1000, originalAmountCents: 700000 })
  })

  it('不同原卖价改单碰撞后保留各价金额，来源只用各自的计划贡献', () => {
    const targets = [target(2, 700), target(3, 800)]
    const [r] = mergeTargetRows({ targets, lots: [lot(2), lot(3)], merges: [], plans: [
      plan('sell', targets[0].id, 900, 300), plan('sell', targets[1].id, 900, 200),
    ] })
    expect(r).toMatchObject({ key: 'sell:T:900', priceCents: 900, qty: 500, amountCents: 450000, originalQty: 1000, originalAmountCents: 750000 })
    expect(r.targets.map(t => t.qty)).toEqual([300, 200])
  })

  it('卖出拆分的原推荐取当前剩余目标量，排除历史已售份额与父批次重复量', () => {
    const ledger = buildLedger([record(2, { soldQty: 200 })], [stock], { extraTargets: [
      { id: 'low', lotId: 'lot:2', priceCents: 700, qty: 300, at: 1 },
      { id: 'middle', lotId: 'lot:2', priceCents: 800, qty: 200, at: 2 },
    ] })
    const rows = mergeTargetRows({ ...ledger, merges: [], plans: [plan('sell', 'target:low', 750, 100)] })
    expect(rows.map(r => [r.originalQty, r.originalAmountCents])).toEqual([[300, 210000], [200, 160000], [300, 270000]])
    expect(rows.reduce((sum, r) => sum + r.originalQty!, 0)).toBe(800)
    expect(rows.map(r => r.qty)).toEqual([100, 200, 300])
  })

  it('卖单目标已经携带计划时也保留原价原量，策略档同价仍独立', () => {
    const targets = [target(2, 700, 500, { planPriceCents: 650, planQty: 100, strategyMode: 'repair' }), target(3, 700, 300, { strategyMode: 'baseT' })]
    const rows = mergeTargetRows({ targets, lots: [lot(2), lot(3, 300)], merges: [] })
    expect(rows).toHaveLength(2)
    expect(rows[0]).toMatchObject({ key: targets[0].id, qty: 100, originalQty: 500, originalAmountCents: 350000 })
    expect(rows[1]).toMatchObject({ key: targets[1].id, qty: 300, originalQty: 300, originalAmountCents: 210000 })
  })
})
