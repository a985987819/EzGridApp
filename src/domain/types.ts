/** 领域类型：对齐规范 §7.1 的字段变更（D1–D7 + P1–P12）。 */

import type { PriceLimitType } from './limit'

export interface StockConfig {
  id: string
  /** 明细里出现的名字，例如「安道麦」 */
  name: string
  /** 代码可空（Excel 里没有） */
  code?: string
  /** 默认卖出间隔，整数分 */
  intervalCents: number
  /** 涨跌幅规则只在股票配置里维护，挂单页直接读它算区间 */
  priceLimitType: PriceLimitType
  customLimitPct?: number | null
  note?: string
  /** 排序序号，拖动调整；0 在最前 */
  order?: number
  /** 停用后只在管理页可见，其他列表/清单不显示（数据仍计入合计） */
  enabled?: boolean
}

/** 从 Excel 解析出来的原始行，尚未派生任何规则字段 */
export interface RawRecord {
  /** Excel 行号，可回溯；手动新增的行从 100000 起（origin='manual'） */
  sourceRow: number
  stockName: string
  buyDateSerial: number | null
  buyPriceCents: number | null
  /** D 列原值；为 null 且 qtyNeedsDerive 时按 FLOOR(6000/买入价,100) 派生 */
  buyQtyRaw: number | null
  qtyNeedsDerive: boolean
  targetPriceCents: number | null
  /** E 列公式无缓存值 → 按 买入价+间隔 重算（D1） */
  targetNeedsDerive: boolean
  soldQty: number | null
  sellDateSerial: number | null
  /** P 列「提前卖的买价」= 回补价（D5） */
  earlyBuyPriceCents: number | null
  /** Excel 里的实现盈利（仅留痕，不参与计算） */
  rawProfitCents: number | null
  importKey: string
  /** 来源：解析导入 or 手动新增 */
  origin?: 'excel' | 'manual'
  /** 软删除时间；非空的行不参与任何计算 */
  deletedAt?: number | null
  /** 最近一次编辑时间 */
  editedAt?: number | null
  /** 由哪一批导入写入，用于回滚（P9 之外补充） */
  batchId?: string | null
}

/** 编辑审计（P10）：实体 / 字段 / 旧值 / 新值 / 时间 / 来源 */
export interface AuditLog {
  id?: number
  entity: 'record' | 'stock'
  entityId: string
  field: string
  oldValue: string
  newValue: string
  at: number
  source: string
}

/** 买入批次（派生对象，不落库） */
export interface Lot {
  id: string
  sourceRow: number
  stockId: string
  stockName: string
  buyDate: string | null
  buyPriceCents: number
  qty: number
  soldQty: number
  remainingQty: number
  targetPriceCents: number | null
  /** 无买入价/目标价 → 标 needsPrice，不出目标（R1 边界） */
  needsPrice: boolean
  importKey: string
}

export type RebuyStatus = 'pending' | 'repaid'
export type PriceSource = 'target' | 'earlyBuy' | 'missing'

/** 卖出成交（派生对象） */
export interface SellExecution {
  id: string
  sourceRow: number
  stockId: string
  stockName: string
  qty: number
  /** 成交价 = E 列（D1） */
  priceCents: number | null
  /** 成本 = 买入价；无批次时取 P 列 */
  costCents: number | null
  profitCents: number | null
  soldAt: string | null
  dateMissing: boolean
  priceSource: PriceSource
  rebuyStatus: RebuyStatus
  /** 卖出日期早于买入日期（D4，合法） */
  sellBeforeBuy: boolean
  /** 成本价分组键 stockId|priceCents */
  groupKey: string | null
  costComplete: boolean
}

export interface SellTarget {
  id: string
  lotId: string
  stockId: string
  stockName: string
  priceCents: number
  qty: number
  autoGenerated: boolean
  /** 预期收益 (E − 成本) × 剩余量 */
  expectProfitCents: number
  amountCents: number
}

export type OrderStatus = 'open' | 'partial' | 'closed' | 'cancelled'

export interface RebuyOrder {
  id: string
  sellExecId: string
  sourceRow: number
  stockId: string
  stockName: string
  rebuyPriceCents: number
  baseQty: number
  rewardQty: number
  status: OrderStatus
  /** 组池信息（R5） */
  groupKey: string
  grossProfitCents: number
  hands: number
  createdAt: number
  /** 无买入批次的卖出 → 真空头敞口；有批次只是回补再买入，不占敞口 */
  exposure: boolean
  /** planPrice/planQty 只在挂单页改，不动真实成交（P8） */
  planPriceCents?: number | null
  planQty?: number | null
}

export interface GroupPool {
  groupKey: string
  stockId: string
  rebuyPriceCents: number
  grossProfitCents: number
  usedProfitCents: number
  capacityHands: number
  grantedHands: number
  availableCents: number
  lotCostCents: number
}

export interface StockSummary {
  stockId: string
  stockName: string
  rows: number
  buyQty: number
  buyAmountCents: number
  sellCount: number
  sellQty: number
  sellAmountCents: number
  profitCents: number
  targetCount: number
  targetQty: number
  targetAmountCents: number
  expectProfitCents: number
  rebuyCount: number
  rebuyQty: number
  netQty: number
  exposureQty: number
}

export interface MonthlyBucket {
  month: string
  sellCount: number
  sellQty: number
  sellAmountCents: number
  profitCents: number
  dateMissing: boolean
}

export interface Anomaly {
  kind: 'needsPrice' | 'dateMissing' | 'negativeProfit'
  sourceRow: number
  stockName: string
  detail: string
}

export interface CheckResult {
  name: string
  ok: boolean
  actual: string
  expected: string
  detail?: string
}

export interface Ledger {
  lots: Lot[]
  sells: SellExecution[]
  targets: SellTarget[]
  orders: RebuyOrder[]
  groups: GroupPool[]
  byStock: StockSummary[]
  monthly: MonthlyBucket[]
  anomalies: Anomaly[]
  checks: CheckResult[]
  totals: {
    rows: number
    buyQty: number
    buyAmountCents: number
    sellCount: number
    sellQty: number
    sellAmountCents: number
    profitCents: number
    targetCount: number
    targetQty: number
    targetAmountCents: number
    expectProfitCents: number
    rebuyCount: number
    rebuyBaseQty: number
    rebuyRewardQty: number
    rebuyQty: number
    rebuyAmountCents: number
    rewardQty: number
    netQty: number
    exposureQty: number
  }
}
