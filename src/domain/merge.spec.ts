import { describe, expect, it } from 'vitest'
import { activeMergeGroupOf, mergeTargetRows } from './merge'
import type { Lot, LotMergeLink, SellTarget, TradePlan } from './types'

function lot(row: number, buyPrice: number, remaining: number, buyDate: string, stock = '柳工'): Lot {
  return {
    id: `lot:${row}`,
    sourceRow: row,
    stockId: `stock:${stock}`,
    stockName: stock,
    buyDate,
    buyPriceCents: buyPrice,
    qty: remaining,
    soldQty: 0,
    remainingQty: remaining,
    targetPriceCents: null,
    needsPrice: false,
    importKey: `k:${row}`,
  }
}

function target(lotId: string, price: number, qty: number): SellTarget {
  return {
    id: `target:${lotId}`,
    lotId,
    stockId: 'stock:柳工',
    stockName: '柳工',
    priceCents: price,
    qty,
    autoGenerated: true,
    expectProfitCents: (price - 961) * qty,
    amountCents: price * qty,
  }
}

const merge: LotMergeLink = {
  id: 'merge:16',
  stockName: '柳工',
  priceCents: 961,
  rows: [16, 22],
  at: 1,
}

describe('activeMergeGroupOf（同价买单合并）', () => {
  it('两笔都还有剩余 → 都归到同一组', () => {
    const map = activeMergeGroupOf(
      [merge],
      [lot(16, 961, 200, '2025-12-01'), lot(22, 961, 600, '2026-03-02')],
    )
    expect(map.get(16)?.id).toBe('merge:16')
    expect(map.get(22)?.id).toBe('merge:16')
  })

  it('只剩一笔在卖（其它卖完了）→ 不合并，但关联本身还在', () => {
    const map = activeMergeGroupOf(
      [merge],
      [lot(16, 961, 200, '2025-12-01'), lot(22, 961, 0, '2026-03-02')],
    )
    expect(map.get(16)).toBeUndefined()
    expect(map.get(22)).toBeUndefined()
  })

  it('买入价被改掉的行自动退出合并（组里买入价必须一致）', () => {
    const map = activeMergeGroupOf(
      [merge],
      [lot(16, 961, 200, '2025-12-01'), lot(22, 900, 600, '2026-03-02')],
    )
    expect(map.get(16)).toBeUndefined()
  })

  it('回补虚拟批次（lot:exec:*）不参与合并', () => {
    const exec: Lot = { ...lot(200001, 961, 500, '2026-03-03'), id: 'lot:exec:x', sourceRow: 200001 }
    const map = activeMergeGroupOf([{ ...merge, rows: [16, 200001] }], [lot(16, 961, 200, '2025-12-01'), exec])
    expect(map.size).toBe(0)
  })
})

describe('mergeTargetRows（挂单提醒的合并显示）', () => {
  const lots = [lot(16, 961, 200, '2025-12-01'), lot(22, 961, 600, '2026-03-02')]
  const targets = [target('lot:16', 1068, 200), target('lot:22', 1068, 600)]

  it('同价位合成一条：数量相加、日期取最早', () => {
    const rows = mergeTargetRows({ targets, lots, merges: [merge] })
    expect(rows).toHaveLength(1)
    const [r] = rows
    expect(r.merged).toBe(true)
    expect(r.key).toBe('merge:16@1068')
    expect(r.priceCents).toBe(1068)
    expect(r.qty).toBe(800)
    expect(r.amountCents).toBe(1068 * 800)
    expect(r.earliestBuyDate).toBe('2025-12-01')
    expect(r.anchorRow).toBe(16)
    expect(r.lotRows).toEqual([16, 22])
    expect(r.targets).toHaveLength(2)
  })

  it('没有手工关联时同价也自动汇总', () => {
    const rows = mergeTargetRows({ targets, lots, merges: [] })
    expect(rows).toHaveLength(1)
    expect(rows[0].qty).toBe(800)
    expect(rows[0].merged).toBe(true)
  })

  it('组内目标价不同 → 各自单列，不跨价合并', () => {
    const split = [target('lot:16', 1068, 200), target('lot:22', 1078, 600)]
    const rows = mergeTargetRows({ targets: split, lots, merges: [merge] })
    expect(rows).toHaveLength(2)
    expect(rows.every((r) => !r.merged)).toBe(true)
    expect(rows.map((r) => r.key)).toEqual(['target:lot:16', 'target:lot:22'])
  })

  it('组里只剩一笔在卖 → 单笔显示，计划价仍按原来的 target', () => {
    const half = [lot(16, 961, 200, '2025-12-01'), lot(22, 961, 0, '2026-03-02')]
    const plans: TradePlan[] = [
      { id: 'plan:target:lot:16', kind: 'sell', refId: 'target:lot:16', priceCents: 1060, qty: 200, at: 1 },
    ]
    const rows = mergeTargetRows({ targets, lots: half, merges: [merge], plans })
    expect(rows.map((r) => r.merged)).toEqual([false])
    const first = rows.find((r) => r.key === 'target:lot:16')
    expect(first?.planPriceCents).toBe(1060)
  })

  it('合并行的计划价挂在组 ref 上', () => {
    const plans: TradePlan[] = [
      { id: 'plan:merge:16@1068', kind: 'sell', refId: 'merge:16@1068', priceCents: 1065, qty: 800, at: 1 },
    ]
    const [r] = mergeTargetRows({ targets, lots, merges: [merge], plans })
    expect(r.planPriceCents).toBe(1065)
    expect(r.planQty).toBe(800)
  })

  it('合并前每笔都有同价计划 → 数量相加当合并行的计划', () => {
    const planned: SellTarget[] = targets.map((t) => ({ ...t, planPriceCents: 1065, planQty: t.qty }))
    const [r] = mergeTargetRows({ targets: planned, lots, merges: [merge] })
    expect(r.planPriceCents).toBe(1065)
    expect(r.planQty).toBe(800)
  })

  it('每笔计划价不同 → 不硬合成一个计划', () => {
    const planned: SellTarget[] = [
      { ...targets[0], planPriceCents: 1065, planQty: 200 },
      { ...targets[1], planPriceCents: 1070, planQty: 600 },
    ]
    const rows = mergeTargetRows({ targets: planned, lots, merges: [merge] })
    expect(rows.map((r)=>r.priceCents)).toEqual([1065,1070])
    expect(rows.map((r)=>r.qty)).toEqual([200,600])
  })

  it('沙盒批次永远不合并', () => {
    const simLots = [lot(300001, 961, 200, '2026-01-01'), lot(22, 961, 600, '2026-03-02')]
    const simTargets = [target('lot:300001', 1068, 200), target('lot:22', 1068, 600)]
    const rows = mergeTargetRows({
      targets: simTargets,
      lots: simLots,
      merges: [{ ...merge, rows: [300001, 22] }],
      sandboxRows: new Set([300001]),
    })
    expect(rows).toHaveLength(2)
    expect(rows.every((r) => !r.merged)).toBe(true)
    expect(rows.find((r) => r.key.startsWith('merge:'))).toBeUndefined()
  })
})
