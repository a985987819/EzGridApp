import { describe, expect, it } from 'vitest'
import * as XLSX from 'xlsx'
import { buildLedger } from './ledger'
import { DEFAULT_STOCKS } from './defaults'
import { DEFAULT_ACCOUNT_ID } from './types'
import { filterByAccount, countByAccount } from './accounts'
import { parseWorkbook } from '../io/parseWorkbook'
import type { ExtraTarget, RawRecord, TradePlan } from './types'

let seq = 2000
function rec(over: Partial<RawRecord> & { stockName: string }): RawRecord {
  seq += 1
  return {
    sourceRow: over.sourceRow ?? seq,
    buyDateSerial: 46000,
    buyPriceCents: null,
    buyQtyRaw: null,
    qtyNeedsDerive: false,
    targetPriceCents: null,
    targetNeedsDerive: false,
    soldQty: null,
    sellDateSerial: null,
    earlyBuyPriceCents: null,
    rawProfitCents: null,
    importKey: `v67-${seq}`,
    ...over,
  }
}

const lot = () =>
  rec({ stockName: '柳工', sourceRow: 1, buyPriceCents: 800, buyQtyRaw: 1000, targetPriceCents: 857 })

function extra(lotId: string, priceCents: number, qty: number, at = 1): ExtraTarget {
  return { id: `et:x${at}`, lotId, priceCents, qty, at }
}

describe('V6 一个批次拆多个卖出目标', () => {
  it('没有拆分时：一个自动目标吃掉全部剩余', () => {
    const l = buildLedger([lot()], DEFAULT_STOCKS)
    expect(l.targets).toHaveLength(1)
    expect(l.targets[0].autoGenerated).toBe(true)
    expect(l.targets[0].qty).toBe(1000)
    expect(l.totals.targetQty).toBe(1000)
  })

  it('拆 400 股到 9.20：自动目标缩到 600，合计仍是 1000', () => {
    const l = buildLedger([lot()], DEFAULT_STOCKS, { extraTargets: [extra('lot:1', 920, 400)] })
    expect(l.targets).toHaveLength(2)
    const manual = l.targets.find((t) => !t.autoGenerated)!
    const auto = l.targets.find((t) => t.autoGenerated)!
    expect(manual.priceCents).toBe(920)
    expect(manual.qty).toBe(400)
    expect(auto.priceCents).toBe(857)
    expect(auto.qty).toBe(600)
    expect(l.totals.targetQty).toBe(1000)
    // 预期收益 = (9.20-8.00)*400 + (8.57-8.00)*600
    expect(l.totals.expectProfitCents).toBe(48000 + 34200)
    for (const c of l.checks) expect(c.ok, `${c.name}: ${c.actual}`).toBe(true)
  })

  it('拆多了（1200 > 1000）：截断到剩余量并标 targetOverflow', () => {
    const l = buildLedger([lot()], DEFAULT_STOCKS, { extraTargets: [extra('lot:1', 920, 1200)] })
    expect(l.targets).toHaveLength(1)
    expect(l.targets[0].qty).toBe(1000)
    expect(l.totals.targetQty).toBe(1000)
    expect(l.anomalies.some((a) => a.kind === 'targetOverflow')).toBe(true)
    for (const c of l.checks) expect(c.ok, `${c.name}: ${c.actual}`).toBe(true)
  })

  it('拆分目标也进价格网格的待卖列', () => {
    const l = buildLedger([lot()], DEFAULT_STOCKS, { extraTargets: [extra('lot:1', 920, 400)] })
    const prices = l.targets.map((t) => t.priceCents).sort((a, b) => a - b)
    expect(prices).toEqual([857, 920])
  })
})

describe('V6 计划价（P8）', () => {
  it('计划价只挂在对象上，不改变任何数字', () => {
    const records = [lot()]
    const base = buildLedger(records, DEFAULT_STOCKS)
    const plan: TradePlan = {
      id: 'plan:target:lot:1',
      kind: 'sell',
      refId: 'target:lot:1',
      priceCents: 999,
      qty: 200,
      at: 1,
    }
    const withPlan = buildLedger(records, DEFAULT_STOCKS, { plans: [plan] })

    expect(withPlan.targets[0].planPriceCents).toBe(999)
    expect(withPlan.targets[0].planQty).toBe(200)
    // 真实口径完全不变
    expect(withPlan.totals.targetAmountCents).toBe(base.totals.targetAmountCents)
    expect(withPlan.totals.expectProfitCents).toBe(base.totals.expectProfitCents)
    expect(withPlan.totals.netQty).toBe(base.totals.netQty)
    expect(withPlan.targets[0].priceCents).toBe(base.targets[0].priceCents)
  })

  it('计划价也能挂在待买订单上', () => {
    const records = [rec({ stockName: '柳工', sourceRow: 2, soldQty: 500, targetPriceCents: 868, earlyBuyPriceCents: 801 })]
    const base = buildLedger(records, DEFAULT_STOCKS)
    const plan: TradePlan = { id: 'plan:rb:sell:2', kind: 'buy', refId: base.orders[0].id, priceCents: 790, qty: 500, at: 1 }
    const l = buildLedger(records, DEFAULT_STOCKS, { plans: [plan] })
    expect(l.orders[0].planPriceCents).toBe(790)
    expect(l.totals.rebuyAmountCents).toBe(base.totals.rebuyAmountCents)
  })
})

describe('V7 账户', () => {
  const records = [
    rec({ stockName: '柳工', sourceRow: 1, accountId: 'acc:a', buyPriceCents: 800, buyQtyRaw: 700, targetPriceCents: 857 }),
    rec({ stockName: '柳工', sourceRow: 2, accountId: 'acc:b', buyPriceCents: 800, buyQtyRaw: 300, targetPriceCents: 857 }),
    rec({ stockName: '柳工', sourceRow: 3, buyPriceCents: 800, buyQtyRaw: 200, targetPriceCents: 857 }),
  ]

  it('activeId=all 不筛；指定账户只留该账户（含老数据落到默认账户）', () => {
    expect(filterByAccount(records, 'all')).toHaveLength(3)
    expect(filterByAccount(records, 'acc:a').map((r) => r.sourceRow)).toEqual([1])
    expect(filterByAccount(records, DEFAULT_ACCOUNT_ID).map((r) => r.sourceRow)).toEqual([3])
  })

  it('按账户过滤后再算账，数字跟着账户走', () => {
    const all = buildLedger(records, DEFAULT_STOCKS)
    const onlyA = buildLedger(filterByAccount(records, 'acc:a'), DEFAULT_STOCKS)
    expect(all.totals.targetQty).toBe(1200)
    expect(onlyA.totals.targetQty).toBe(700)
    for (const c of onlyA.checks) expect(c.ok, `${c.name}: ${c.actual}`).toBe(true)
  })

  it('countByAccount 跳过软删除', () => {
    const withDeleted = [...records, { ...records[0], sourceRow: 9, deletedAt: 1 }]
    const counts = countByAccount(withDeleted)
    expect(counts.get('acc:a')).toBe(1)
    expect(counts.get(DEFAULT_ACCOUNT_ID)).toBe(1)
  })
})

describe('V7 导入模板兼容（英文表头）', () => {
  it('英文表头也能解析出记录', async () => {
    const rows = [
      ['stock', 'date', 'buy price', 'shares', 'target price', 'sold qty', 'sell date', 'rebuy'],
      ['柳工', 46050, 11.48, 500, 11.98, 500, 46080, ''],
      ['三一重工', 46097, 21, 500, 21.68, 500, 46153, ''],
    ]
    const ws = XLSX.utils.aoa_to_sheet(rows)
    const wb = XLSX.utils.book_new()
    XLSX.utils.book_append_sheet(wb, ws, '交易记录')
    const buf = XLSX.write(wb, { type: 'array', bookType: 'xlsx' }) as ArrayBuffer

    const parsed = await parseWorkbook(new Uint8Array(buf))
    expect(parsed.missingColumns).toHaveLength(0)
    expect(parsed.records).toHaveLength(2)
    expect(parsed.records[0].stockName).toBe('柳工')
    expect(parsed.records[0].buyPriceCents).toBe(1148)
    expect(parsed.records[0].soldQty).toBe(500)
    expect(parsed.records[1].stockName).toBe('三一重工')
    expect(parsed.records[1].targetPriceCents).toBe(2168)
  })
})
