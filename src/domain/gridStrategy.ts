import type { ExtraTarget, Ledger, Lot, RawRecord, RebuyExecution } from './types'
import { isSellFirst } from './sellFirst'
import { deriveBuyQty } from './qty'
import { remainingSellTargets } from './sellTargets'

export type GridMode = 'repair' | 'baseT'

/** 同行回补多买的份额不是做T还仓，继续使用原行普通目标。 */
export function baseTSurplusTargets(records: readonly RawRecord[], targets: readonly ExtraTarget[], baseAmountYuan = 6000): ExtraTarget[] {
  const modes = strategySales(records, targets)
  return records.flatMap(r => {
    const marker = modes.get(r.sourceRow)
    if (r.deletedAt || !isSellFirst(r) || marker?.strategy?.mode !== 'baseT' || r.buyDateSerial === null || r.sellDateSerial === null || r.sellDateSerial > r.buyDateSerial) return []
    const qty = r.buyQtyRaw ?? (r.qtyNeedsDerive && r.buyPriceCents ? deriveBuyQty(r.buyPriceCents, baseAmountYuan) : 0)
    const surplus = qty - (r.soldQty ?? 0)
    return surplus > 0 && r.targetPriceCents ? [{id:`baseT-surplus:${r.sourceRow}`,lotId:`lot:${r.sourceRow}`,priceCents:r.targetPriceCents,qty:surplus,at:marker.at}] : []
  })
}
export interface LadderInput {
  lotIds: string[]
  startCents: number
  stepCents: number
  direction: 1 | -1
  perQty: number
  rebuyGapCents: number
  mode: GridMode
  targetIds?: string[]
}

/** 只拆当前未被手动档占用的自动档；先预览、保存时用最新账本再验证。 */
export function buildLadder(ledger: Pick<Ledger, 'lots' | 'targets'>, input: LadderInput, groupId: string, at: number): ExtraTarget[] {
  if (!input.lotIds.length || new Set(input.lotIds).size !== input.lotIds.length) throw new Error('请选择不重复的来源批次')
  if (![input.startCents, input.stepCents, input.perQty, input.rebuyGapCents].every(n => Number.isSafeInteger(n) && n > 0)
    || ![1, -1].includes(input.direction) || !['repair', 'baseT'].includes(input.mode)) throw new Error('起始价、档距、每档股数和回补价差必须为正数')
  const stocks = new Set(input.lotIds.map(id => ledger.lots.find(l => l.id === id)?.stockName))
  if (stocks.size !== 1 || stocks.has(undefined)) throw new Error('来源批次必须属于同一股票')
  const out: ExtraTarget[] = []
  let index = 0
  for (const lotId of input.lotIds) {
    const lot = ledger.lots.find(l => l.id === lotId)!
    if (lot.strategyOrigin?.mode === 'baseT' && input.mode !== 'baseT') throw new Error('恢复底仓的份额继续使用底仓做T；不能将已有做T库存自动迁入回本链')
    let left = ledger.targets.filter(t => t.lotId === lotId && (input.targetIds ? input.targetIds.includes(t.id) : t.autoGenerated)).reduce((a, t) => a + t.qty, 0)
    if (left <= 0) throw new Error('来源已被占用或没有可拆份额，请重新选择')
    while (left > 0) {
      if (index >= 500) throw new Error('一次最多生成500档，请增大每档股数')
      const p = input.startCents + input.direction * input.stepCents * index
      const rebuy = p - input.rebuyGapCents
      if (!Number.isSafeInteger(p) || !Number.isSafeInteger(rebuy) || rebuy <= 0 || !lot.targetPriceCents) throw new Error('存在非正价位或来源缺少原卖出目标')
      const qty = Math.min(left, input.perQty)
      out.push({ id: `grid:${groupId}:${index++}`, lotId, priceCents: p, qty, at,
        strategy: { mode: input.mode, rebuyPriceCents: rebuy, nextSellPriceCents: input.mode === 'baseT' ? lot.targetPriceCents : p, groupId } })
      left -= qty
    }
  }
  return out
}

/** 成交沿明确来源档读取策略；普通成交不会因碰价自动变为做T。 */
export function strategySales(records: readonly RawRecord[], targets: readonly ExtraTarget[], executions: readonly RebuyExecution[] = []): Map<number, ExtraTarget> {
  const byId = new Map(targets.filter(t => t.strategy).map(t => [`target:${t.id}`, t]))
  const out = new Map(records.filter(r => !r.deletedAt && r.soldTargetId && byId.has(r.soldTargetId)).map(r => [r.sourceRow, byId.get(r.soldTargetId!)!]))
  for (const target of targets) if (target.strategy?.sellRow !== undefined && records.some(r => !r.deletedAt && r.sourceRow === target.strategy?.sellRow)) out.set(target.strategy.sellRow, target)
  const parents = new Map(executions.map(e => [`lot:exec:${e.id}`, Number(e.sellExecId.replace('sell:', ''))]))
  let changed = true
  while (changed) {
    changed = false
    for (const r of records) {
      if (r.deletedAt || out.has(r.sourceRow) || !r.soldLotId) continue
      const parent = out.get(parents.get(r.soldLotId) ?? -1)
      if (parent?.strategy?.mode === 'repair') { out.set(r.sourceRow, parent);changed = true }
    }
  }
  return out
}

export interface GridStatus {
  id: string; lotId: string; stockName: string; mode: GridMode; qty: number; unfilledQty: number
  soldQty: number; repaidQty: number; pendingQty: number; holdingQty: number; spreadCents: number
  sellPriceCents: number; rebuyPriceCents: number; nextSellPriceCents: number
}
export function gridStatuses(targets: readonly ExtraTarget[], records: readonly RawRecord[], executions: readonly RebuyExecution[], lots: readonly Lot[]): GridStatus[] {
  const surplus = remainingSellTargets(baseTSurplusTargets(records, targets), records)
  return targets.filter(t => t.strategy).map(t => {
    const sales = records.filter(r => !r.deletedAt && (r.soldTargetId === `target:${t.id}` || r.sourceRow === t.strategy?.sellRow))
    const soldQty = sales.reduce((a, r) => a + (r.soldQty ?? 0), 0)
    const execs = executions.filter(e => sales.some(r => e.sellExecId === `sell:${r.sourceRow}`))
    const ownQty = (r: RawRecord) => r.buyDateSerial !== null && r.sellDateSerial !== null && r.sellDateSerial <= r.buyDateSerial && r.buyPriceCents !== null && !r.soldLotId
      ? Math.min(r.soldQty ?? 0, r.buyQtyRaw ?? (r.qtyNeedsDerive ? deriveBuyQty(r.buyPriceCents) : 0)) : 0
    const repaidQty = sales.reduce((a,r)=>a+ownQty(r),0) + execs.reduce((a, e) => a + e.qty - e.rewardQty, 0)
    const spreadCents = sales.reduce((sum, r) => sum + ((r.targetPriceCents ?? 0) - (r.buyPriceCents ?? 0)) * ownQty(r) + execs.filter(e => e.sellExecId === `sell:${r.sourceRow}`)
      .reduce((a, e) => a + ((r.targetPriceCents ?? 0) - e.priceCents) * (e.qty - e.rewardQty), 0), 0)
    return { id: t.id, lotId: t.lotId, stockName: lots.find(l => l.id === t.lotId)?.stockName ?? '', mode: t.strategy!.mode,
      qty: t.strategy?.sellRow !== undefined ? soldQty : t.qty, unfilledQty: t.strategy?.sellRow !== undefined ? 0 : Math.max(0, t.qty - soldQty), soldQty, repaidQty, pendingQty: Math.max(0, soldQty - repaidQty), spreadCents,
      holdingQty: sales.reduce((a,r)=>a+Math.max(0,Math.min(ownQty(r),(lots.find(l=>l.id===`lot:${r.sourceRow}`)?.remainingQty??0)-(surplus.find(s=>s.lotId===`lot:${r.sourceRow}`)?.qty??0))),0)
        + execs.reduce((a, e) => a + (lots.find(l => l.id === `lot:exec:${e.id}`)?.remainingQty ?? 0), 0),
      sellPriceCents: t.priceCents, rebuyPriceCents: t.strategy!.rebuyPriceCents, nextSellPriceCents: t.strategy!.nextSellPriceCents }
  })
}
